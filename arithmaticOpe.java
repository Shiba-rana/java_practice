public class arithmaticOpe {
    public static void main(String args[]) {
        int a = 10, b = 3;

        // Add
        System.out.println(a + b);

        // Minus
        System.out.println(a - b);

        // Mul
        System.out.println(a * b);

        // Div
        System.out.println(a / b); // 3
        System.out.println(a / (float)b); // 3.333

        // Modulo ope
        System.out.println(a % b);
        
    }
}
